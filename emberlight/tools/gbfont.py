def glyph_rows(ch):
    """Return the 7 ink rows for a character, falling back to blank."""
    return G.get(ch, G[' '])


def glyph_bitmap(ch):
    """Return an 8x8 list of lists of 0/1 for a character."""
    cell = [[0] * CELL_W for _ in range(CELL_H)]
    if ch in FULL:
        for y, row in enumerate(FULL[ch]):
            for x, c in enumerate(row):
                if c == '#':
                    cell[y][x] = 1
        return cell
    rows = glyph_rows(ch)
    for y, row in enumerate(rows):
        for x, c in enumerate(row):
            if c == '#':
                cell[y + GLYPH_Y][x + GLYPH_X] = 1
    return cell


def font_tiles():
    """All 64 ROM font cells, in ASCII order, as 8x8 0/1 bitmaps."""
    out = []
    for code in range(FONT_FIRST, FONT_LAST + 1):
        out.append(glyph_bitmap(chr(code)))
    return out


def text_width(s, tracking=6):
    return len(s) * tracking


def draw_text(put, s, x, y, tracking=6, scale=1):
    """Rasterise `s` by calling put(px, py) for every ink pixel.

    `tracking` is the horizontal advance in unscaled pixels; 6 gives the
    tight look used by the title cards, 8 matches the tile grid.
    """
    cx = x
    for ch in s.upper():
        rows = glyph_rows(ch)
        for gy, row in enumerate(rows):
            for gx, c in enumerate(row):
                if c != '#':
                    continue
                for sy in range(scale):
                    for sx in range(scale):
                        put(cx + gx * scale + sx, y + gy * scale + sy)
        cx += tracking * scale
    return cx
